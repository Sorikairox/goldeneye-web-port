#!/usr/bin/env python3
"""Generate the inputs of the in-browser sidecar converter (port/src/web/geconvweb.c).

    gen_geconv_inputs.py FILELIST.csv RESTABLE.inc.c ASSETS_DIR OUT.c

Emits the filelist CSV and file_resource_table.inc.c texts as C strings (ROM offsets and file
names only), and the list of model header objects the converters need (MODELFILEHEADER stems,
selected with the same rule as tools_pc/d43_emit.py: numSwitches/numTextures arguments parse as
Python ints). The counts themselves are NOT emitted: they are read from the game's own
<stem>_header objects at run time (weak references; NULL when a header is not linked).
"""
import os
import re
import sys


def cstr(name, data):
    out = ['const char %s[] =' % name]
    for i in range(0, len(data), 96):
        chunk = data[i:i + 96]
        s = ''.join(c if 32 <= ord(c) < 127 and c not in '"\\?' else '\\%03o' % ord(c) for c in chunk)
        out.append('  "%s"' % s)
    out[-1] += ';'
    out.append('const unsigned long %s_len = %d;' % (name, len(data)))
    return '\n'.join(out) + '\n'


def main():
    filelist, restable, assets, outp = sys.argv[1:5]
    stems = []
    seen = set()
    for root, dirs, files in sorted(os.walk(assets)):
        dirs.sort()
        for fn in sorted(files):
            if not fn.lower().endswith('modelfileheader.inc.c'):
                continue
            for line in open(os.path.join(root, fn), errors='replace'):
                m = re.search(r"MODELFILEHEADER\((.*)\)\s*;?\s*$", line)
                if not m:
                    continue
                a = [x.strip() for x in m.group(1).split(',')]
                if len(a) < 9:
                    continue
                try:
                    int(a[4], 0), int(a[8], 0)
                except ValueError:
                    continue
                if a[0] not in seen and re.match(r'^\w+$', a[0]):
                    seen.add(a[0])
                    stems.append(a[0])
    out = ['/* Generated by scripts/web/gen_geconv_inputs.py -- do not edit. Names and offsets only. */',
           '#include <ultra64.h>', '#include <bondgame.h>', '']
    out.append(cstr('ge_geconv_filelist', open(filelist, newline='').read()))
    out.append(cstr('ge_geconv_restable', open(restable, newline='').read()))
    for s in stems:
        out.append('extern struct ModelFileHeader %s_header __attribute__((weak));' % s)
    out.append('struct GeconvHeaderRef { const char *stem; const unsigned char *hdr; };')
    out.append('const struct GeconvHeaderRef ge_geconv_headers[] = {')
    for s in stems:
        out.append('  { "%s", (const unsigned char *)&%s_header },' % (s, s))
    out.append('};')
    out.append('const int ge_geconv_nheaders = %d;' % len(stems))
    out.append('const int ge_geconv_off_numswitches = __builtin_offsetof(struct ModelFileHeader, numSwitches);')
    out.append('const int ge_geconv_off_numtextures = __builtin_offsetof(struct ModelFileHeader, numtextures);')
    open(outp, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
