// G9 offline play: write <site>/sw-build.js for the service worker (port/web/sw.js): the precache list (every regular
// file of the site except the worker's own two files and dev markers) and a build id = SHA-256 over the names and
// contents, so any changed file gives a new cache name. Run by scripts/web/build.sh on build-web/site and by
// scripts/web/deploy_web.sh on the publish directory (after BUILD.txt). Prints the precache total.
//   node scripts/web/swbuild.mjs <site-dir>
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
const dir = process.argv[2];
if (!dir || !fs.existsSync(dir)) { console.error('usage: swbuild.mjs <site-dir>'); process.exit(2); }
const skip = new Set(['sw.js', 'sw-build.js', 'DEV-UNSTRIPPED']);
const files = fs.readdirSync(dir).filter((f) => !skip.has(f) && !f.startsWith('.') && fs.statSync(path.join(dir, f)).isFile()).sort();
const all = crypto.createHash('sha256'); let bytes = 0;
for (const f of files) {
  const d = fs.readFileSync(path.join(dir, f)); bytes += d.length;
  all.update(f + '\0' + crypto.createHash('sha256').update(d).digest('hex') + '\n');
}
const build = all.digest('hex').slice(0, 16);
fs.writeFileSync(path.join(dir, 'sw-build.js'),
  `// generated by scripts/web/swbuild.mjs: the offline precache list (port/web/sw.js)\n` +
  `self.GE_BUILD = '${build}';\nself.GE_BYTES = ${bytes};\nself.GE_FILES = ${JSON.stringify(files)};\n`);
console.log(`swbuild: ${files.length} files, ${(bytes / 1048576).toFixed(2)} MiB, build ${build}`);
