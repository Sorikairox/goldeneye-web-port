#!/usr/bin/env python3
"""Call-signature adapters for the web build (docs/web/PLAN.md "Calls").

The decomp calls a few dozen functions through a prototype that differs from the
definition (implicit declarations, `extern f32 f()` vs `int f()`, missing or extra
arguments). MIPS and x86-64 tolerate that (arguments in registers); wasm does not: the
linker turns such a call into a trap ("signature_mismatch:<fn>").

The fix keeps the game code unmodified: in the CALLING translation unit the function name
is redirected (-Dfn=ge_sa_fn_N) to a generated adapter with the caller's wasm signature,
which converts the arguments the way a register-passing ABI would (i32 -> i64 zero-
extended, i64 -> i32 truncated, missing arguments 0, extra ones dropped, f32/f64 <-> int
numeric) and calls the real definition. The list is data: scripts/web/sigadapt.tsv.

  sigadapt.py scan BUILD_LOG BUILD_DIR   add new wasm-ld "function signature mismatch"
                                         warnings to sigadapt.tsv (run in the container)
  sigadapt.py gen OUT.c OUT.cmake        write the adapters and the per-source defines
                                         (CMake runs this at configure time)
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TSV = os.path.join(HERE, "sigadapt.tsv")
CT = {"i32": "int32_t", "i64": "int64_t", "f32": "float", "f64": "double", "void": "void"}


def read_tsv():
    rows = []
    if os.path.exists(TSV):
        for line in open(TSV):
            if line.startswith("#") or not line.strip():
                continue
            f = line.rstrip("\n").split("\t")
            rows.append({"sym": f[0], "caller": f[1], "call": f[2], "defn": f[3],
                         "note": f[4] if len(f) > 4 else ""})
    return rows


def write_tsv(rows):
    with open(TSV, "w") as o:
        o.write("# symbol\tcaller TU (basename)\tcaller's wasm signature\tdefinition's wasm signature\tnote\n")
        o.write("# Generated by scripts/web/sigadapt.py scan; reviewed by hand (see the note column).\n")
        for r in sorted(rows, key=lambda r: (r["sym"], r["caller"])):
            o.write("\t".join([r["sym"], r["caller"], r["call"], r["defn"], r["note"]]) + "\n")


def parse_sig(s):
    m = re.match(r"\((.*)\)\s*->\s*(\w+)", s.strip())
    args = [a.strip() for a in m.group(1).split(",") if a.strip()]
    return args, m.group(2)


def scan(log, builddir):
    rows = read_tsv()
    have = {(r["sym"], r["caller"]) for r in rows}
    text = open(log).read()
    pat = re.compile(r"function signature mismatch: (\S+)\n>>> defined as (.*?) in (\S+)\n>>> defined as (.*?) in (\S+)")
    nm = "/emsdk/upstream/bin/llvm-nm"
    added = 0
    for sym, s1, o1, s2, o2 in pat.findall(text):
        def defines(obj):
            if not obj.endswith(".o") or "(" in obj:
                return False
            p = obj if os.path.isabs(obj) else os.path.join(builddir, obj)
            out = subprocess.run([nm, "--defined-only", p], capture_output=True, text=True).stdout
            return any(l.split()[-1] == sym and l.split()[-2] in "TtWw" for l in out.splitlines() if l.split())
        if defines(o2):
            call, caller, defn = s1, o1, s2
        elif defines(o1):
            call, caller, defn = s2, o2, s1
        else:
            print("sigadapt: cannot tell the definition of %s (%s / %s); skipped" % (sym, o1, o2))
            continue
        if "(" in caller:      # a library (SDL) calling a libc name the game redefines
            print("sigadapt: %s called from library %s; needs a rename, skipped" % (sym, caller))
            continue
        base = os.path.basename(caller)[:-2]          # foo.c.o -> foo.c
        if (sym, base) in have:
            continue
        rows.append({"sym": sym, "caller": base, "call": call, "defn": defn, "note": ""})
        have.add((sym, base))
        added += 1
    write_tsv(rows)
    print("sigadapt: %d new adapter(s), %d total" % (added, len(rows)))


def conv(val, frm, to):
    if frm == to:
        return val
    if frm == "i32" and to == "i64":
        return "(int64_t)(uint32_t)(%s)" % val       # zero-extend, like a 32-bit register write
    if frm == "i64" and to == "i32":
        return "(int32_t)(%s)" % val
    return "(%s)(%s)" % (CT[to], val)                 # numeric float <-> int conversions


def gen(out_c, out_cmake):
    rows = read_tsv()
    c = ["/* AUTO-GENERATED by scripts/web/sigadapt.py from scripts/web/sigadapt.tsv -- do not edit. */",
         "#include <stdint.h>", ""]
    cm = ["# AUTO-GENERATED by scripts/web/sigadapt.py -- per-source redirects to the adapters"]
    defs = {}
    for n, r in enumerate(rows):
        cargs, cret = parse_sig(r["call"])
        dargs, dret = parse_sig(r["defn"])
        name = "ge_sa_%s_%d" % (r["sym"], n)
        c.append("/* %s: %s calls it as %s, defined as %s. %s */" % (r["sym"], r["caller"], r["call"], r["defn"], r["note"]))
        c.append("extern %s %s(%s);" % (CT[dret], r["sym"], ", ".join(CT[a] for a in dargs) or "void"))
        params = ", ".join("%s a%d" % (CT[a], i) for i, a in enumerate(cargs)) or "void"
        c.append("%s %s(%s)" % (CT[cret], name, params))
        call_args = []
        for i, a in enumerate(dargs):
            call_args.append(conv("a%d" % i, cargs[i], a) if i < len(cargs) else "0")
        call = "%s(%s)" % (r["sym"], ", ".join(call_args))
        if cret == "void":
            body = "%s;" % call
        elif dret == "void":
            body = "%s; return 0;" % call
        else:
            body = "return %s;" % conv(call, dret, cret)
        c.append("{ %s }" % body)
        c.append("")
        defs.setdefault(r["caller"], []).append("%s=%s" % (r["sym"], name))
    for caller, d in sorted(defs.items()):
        cm.append('list(APPEND GE_SIGADAPT_DEFS "%s|%s")' % (caller, ";".join(d).replace(";", ",")))
    open(out_c, "w").write("\n".join(c) + "\n")
    open(out_cmake, "w").write("\n".join(cm) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "scan":
        scan(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "gen":
        gen(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
